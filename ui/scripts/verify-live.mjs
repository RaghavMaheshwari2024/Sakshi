// Live-mode checks (run against a backend or the stub): node scripts/verify-live.mjs <vite-url> <api-url>
import puppeteer from 'puppeteer-core';
const [BASE, API] = process.argv.slice(2);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let failed = 0;
const check = (n, ok, d = '') => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${d !== '' ? `  (${d})` : ''}`); if (!ok) failed++; };
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
await page.evaluateOnNewDocument(() => localStorage.setItem('sakshi_guide_seen', 'true'));
const text = () => page.evaluate(() => document.body.innerText);
const click = (label) => page.evaluate((l) => { const b = [...document.querySelectorAll('button')].filter((x) => x.offsetParent).find((x) => (x.innerText || x.getAttribute('aria-label') || '').trim().includes(l)); b?.click(); return Boolean(b); }, label);
const state = async () => (await fetch(`${API}/__state`)).json();

await page.goto(`${BASE}/?view=case&scenario=base`, { waitUntil: 'networkidle2' });
await wait(800);
await click('Side impact, clear day');
await wait(900);
check('Backend cases listed in the switcher', (await text()).toLowerCase().includes('on this backend') && (await text()).includes('live01'));
await click('live01');
await wait(900);
const cal = await text();
check('Unrun case goes to calibration', cal.includes('Fit quality'));
check('It is not read-only', !cal.includes('pre-rendered scenario'));
await click('Synthetic preset');
await wait(200);
await click('Save');
await wait(500);
check('Save shows the backend’s own fit', (await text()).includes('0.321'));
await click('Run pipeline');
await page.waitForFunction(() => document.body.innerText.includes('Live from the backend'), { timeout: 5000 });
check('Run opens in live mode', true);
await page.waitForFunction(() => document.body.innerText.includes('Who drove what?'), { timeout: 6000 });
check('Repeated stage events merge', (await text()).includes('18 drops recovered') && (await text()).includes('8 ticks read'));
await page.evaluate(() => { const s = document.querySelector('[role=dialog] select'); const set = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; set.call(s, 'car-1'); s.dispatchEvent(new Event('change', { bubbles: true })); });
await wait(100);
await click('Confirm');
await page.waitForFunction(() => document.body.innerText.includes('Number check passed'), { timeout: 15000 }).catch(() => null);
await wait(4000);
const st = await state();
check('Reassignment posts /party and re-runs', st.party?.s1 === 'car-1' && st.runs >= 2, JSON.stringify(st));
await page.waitForFunction(() => document.body.innerText.includes('Open the result'), { timeout: 15000 });
await page.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.innerText.includes('Open the result')).click());
await wait(1000);
check('Result opens in the workspace', (await text()).includes('Walk through this case'));
check('Backend case is on screen', await page.evaluate(() => window.sakshiStore.getState().backendCaseId === 'live01' && window.sakshiStore.getState().videoUrl === '/cases/live01/video'));
await fetch(`${API}/__fail`);
await click('Pipeline run');
await wait(300);
await click('Run on backend');
await page.waitForFunction(() => document.body.innerText.includes('SAM request failed'), { timeout: 6000 }).catch(() => null);
check('Server error is shown as is', (await text()).includes('SAM request failed: 503'));
check('Recorded run offered after a failure', (await text()).includes('Show recorded run'));
await browser.close();
console.log(failed ? `\n${failed} FAILED` : '\nALL PASSED');
process.exit(failed ? 1 : 0);
